package com.givebackmyoneplus

import android.content.ContentValues
import android.content.Context
import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.LinearGradient
import android.graphics.Paint
import android.graphics.RadialGradient
import android.graphics.Shader
import android.net.Uri
import android.os.Environment
import android.provider.MediaStore
import java.io.ByteArrayOutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * Собирает тему HyperOS (.mtz — zip-архив):
 *  description.xml, icons (вложенный zip с иконками по именам пакетов),
 *  wallpaper/, preview/.
 */
object MtzBuilder {

    private const val ICON_SIZE = 192

    data class Result(val uri: Uri, val fileName: String, val iconCount: Int)

    /** Блокирующий вызов. */
    fun build(
        context: Context,
        accent: Int,
        shape: IconShape,
        style: IconStyle,
        progress: (String) -> Unit,
    ): Result {
        val apps = Apps.launcherApps(context)
        val hex = String.format("%06X", accent and 0xFFFFFF)
        val title = "OxygenStyle #$hex"

        progress("Рисую иконки (${apps.size})…")
        val icons = ByteArrayOutputStream()
        ZipOutputStream(icons).use { zip ->
            apps.forEachIndexed { i, app ->
                if (i % 10 == 0) progress("Иконки: $i / ${apps.size}")
                val bmp = IconRenderer.render(app.icon, ICON_SIZE, shape, style, accent)
                zip.putBitmap("res/drawable-xxhdpi/${app.pkg}.png", bmp, Bitmap.CompressFormat.PNG)
            }
            // Подложка и маска для приложений, которых нет в списке (установленных позже).
            val bg = if (style == IconStyle.MONO) 0xFF1E1E21.toInt() else accent
            zip.putBitmap("res/drawable-xxhdpi/icon_background.png",
                IconRenderer.shapeBitmap(ICON_SIZE, shape, bg), Bitmap.CompressFormat.PNG)
            zip.putBitmap("res/drawable-xxhdpi/icon_mask.png",
                IconRenderer.shapeBitmap(ICON_SIZE, shape, Color.WHITE), Bitmap.CompressFormat.PNG)
        }

        progress("Рисую обои…")
        val wallpaper = wallpaper(accent)
        val preview = preview(wallpaper, apps.take(16), shape, style, accent)

        progress("Упаковываю тему…")
        val fileName = "OxygenStyle_$hex.mtz"
        val values = ContentValues().apply {
            put(MediaStore.Downloads.DISPLAY_NAME, fileName)
            put(MediaStore.Downloads.MIME_TYPE, "application/octet-stream")
            put(MediaStore.Downloads.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS + "/givebackmyOneplus")
        }
        val resolver = context.contentResolver
        val uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values)
            ?: throw IllegalStateException("Не удалось создать файл в Загрузках")
        resolver.openOutputStream(uri)!!.use { out ->
            ZipOutputStream(out).use { zip ->
                zip.putBytes("description.xml", description(title).toByteArray())
                zip.putBytes("icons", icons.toByteArray())
                zip.putBitmap("wallpaper/default_wallpaper.jpg", wallpaper, Bitmap.CompressFormat.JPEG)
                zip.putBitmap("wallpaper/default_lock_wallpaper.jpg", wallpaper, Bitmap.CompressFormat.JPEG)
                zip.putBitmap("preview/preview_icons_0.jpg", preview, Bitmap.CompressFormat.JPEG)
            }
        }
        return Result(uri, fileName, apps.size)
    }

    private fun ZipOutputStream.putBytes(name: String, bytes: ByteArray) {
        putNextEntry(ZipEntry(name))
        write(bytes)
        closeEntry()
    }

    private fun ZipOutputStream.putBitmap(name: String, bmp: Bitmap, format: Bitmap.CompressFormat) {
        val buf = ByteArrayOutputStream()
        bmp.compress(format, 92, buf)
        putBytes(name, buf.toByteArray())
    }

    private fun description(title: String) = """
        <?xml version="1.0" encoding="UTF-8"?>
        <theme>
            <title>$title</title>
            <designer>givebackmyOneplus</designer>
            <author>givebackmyOneplus</author>
            <version>1.0</version>
            <uiVersion>14</uiVersion>
            <description>OxygenOS 16 style theme generated by givebackmyOneplus</description>
        </theme>
    """.trimIndent()

    /** Тёмные обои с мягким свечением акцентного цвета. */
    private fun wallpaper(accent: Int): Bitmap {
        val w = 1080
        val h = 2400
        val bmp = Bitmap.createBitmap(w, h, Bitmap.Config.ARGB_8888)
        val c = Canvas(bmp)
        c.drawColor(Color.BLACK)
        val glow = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            shader = RadialGradient(w * 0.8f, h * 0.85f, w * 1.1f,
                intArrayOf(withAlpha(accent, 200), withAlpha(accent, 40), Color.TRANSPARENT),
                floatArrayOf(0f, 0.55f, 1f), Shader.TileMode.CLAMP)
        }
        c.drawRect(0f, 0f, w.toFloat(), h.toFloat(), glow)
        val glow2 = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            shader = RadialGradient(w * 0.1f, h * 0.2f, w * 0.7f,
                intArrayOf(withAlpha(accent, 70), Color.TRANSPARENT), null, Shader.TileMode.CLAMP)
        }
        c.drawRect(0f, 0f, w.toFloat(), h.toFloat(), glow2)
        val fade = Paint().apply {
            shader = LinearGradient(0f, 0f, 0f, h.toFloat(),
                intArrayOf(0x66000000, Color.TRANSPARENT, 0x88000000.toInt()), null, Shader.TileMode.CLAMP)
        }
        c.drawRect(0f, 0f, w.toFloat(), h.toFloat(), fade)
        return bmp
    }

    private fun preview(wallpaper: Bitmap, apps: List<LauncherApp>, shape: IconShape, style: IconStyle, accent: Int): Bitmap {
        val bmp = Bitmap.createScaledBitmap(wallpaper, 540, 1200, true).copy(Bitmap.Config.ARGB_8888, true)
        val c = Canvas(bmp)
        val size = 96
        val cell = 540 / 4f
        apps.forEachIndexed { i, app ->
            val icon = IconRenderer.render(app.icon, size, shape, style, accent)
            val x = cell * (i % 4) + (cell - size) / 2
            val y = 160f + (i / 4) * 170f
            c.drawBitmap(icon, x, y, null)
        }
        return bmp
    }

    private fun withAlpha(color: Int, alpha: Int) =
        Color.argb(alpha, Color.red(color), Color.green(color), Color.blue(color))
}
